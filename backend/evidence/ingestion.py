"""Normalize provider evidence without inferring road closures from gauge heights.

Provider failures are isolated. Cached payload timestamps remain provider times;
receipt time is generated by Store. No external calls happen in DB transactions.
"""

from __future__ import annotations

import asyncio
import logging
from typing import Any

from pydantic import ValidationError

from evidence.store import Store
from feeds.nws import active_alerts
from feeds.usgs_flood_impacts import flood_impacts
from feeds.usgs_ogc import gage_height

log = logging.getLogger(__name__)


def _warnings(envelope: dict[str, Any]) -> list[dict[str, Any]]:
    raw_features = (envelope.get("data") or {}).get("features", [])
    originals = {str((f.get("properties") or {}).get("id") or f.get("id")): f
                 for f in raw_features if isinstance(f, dict)}
    rows = []
    for item in envelope.get("alerts", []):
        if "flood" not in str(item.get("event", "")).lower():
            continue
        original = originals.get(str(item.get("id")), item)
        props = original.get("properties") or {}
        rows.append({"source_id": "nws_alerts", "source_record_id": str(item.get("id") or "unknown-alert"),
                     "kind": "warning", "observed_at": props.get("sent") or props.get("effective"),
                     "valid_until": item.get("expires"), "geometry": item.get("polygon"),
                     "quality": "agency", "raw": original})
    return rows


def _gauges(envelope: dict[str, Any]) -> list[dict[str, Any]]:
    location = envelope.get("monitoring_location_id") or "USGS-08166200"
    latest_mode = envelope.get("source", "unavailable")
    series_mode = envelope.get("series_source", latest_mode)
    points = [(p, series_mode) for p in envelope.get("series_24h", []) if series_mode != "unavailable"]
    if envelope.get("latest"):
        points.append((envelope["latest"], latest_mode if latest_mode != "unavailable" else series_mode))
    return [{"source_id": "usgs_gage", "source_record_id": f"{location}:{p.get('time')}",
             "kind": "gauge", "observed_at": p.get("time"), "value": p.get("value_ft"),
             "unit": "ft", "quality": "sensor", "source_mode": mode, "raw": {"monitoring_location_id": location,
             "measurement": p, "measurement_type": "gage_height", "datum": "station_gage_datum"}}
            for p, mode in points if isinstance(p, dict)]


def _impacts(envelope: dict[str, Any]) -> list[dict[str, Any]]:
    rows = []
    for item in envelope.get("impacts", []):
        geometry = None
        if item.get("lon") is not None and item.get("lat") is not None:
            geometry = {"type": "Point", "coordinates": [item["lon"], item["lat"]]}
        # Reference thresholds describe where impacts may occur. They are neither
        # newly observed flooding nor an assertion that a road is passable.
        rows.append({"source_id": "usgs_flood_impacts", "source_record_id": str(item.get("id") or item.get("name")),
                     "kind": "report", "observed_at": None, "geometry": geometry,
                     "value": item.get("flood_stage_ft"), "unit": "ft", "quality": "agency",
                     "raw": {"reference_point": item, "measurement_type": "impact_threshold",
                             "note": "Reference context only; observation time is unknown"}})
    return rows


async def ingest_feeds(store: Store) -> dict[str, Any]:
    """Fetch NWS and USGS independently, persist valid records, report source health."""
    adapters = [("nws_alerts", active_alerts, _warnings),
                ("usgs_gage", gage_height, _gauges),
                ("usgs_flood_impacts", flood_impacts, _impacts)]
    envelopes = await asyncio.gather(*(fetch() for _, fetch, _ in adapters), return_exceptions=True)
    return await asyncio.to_thread(_persist_envelopes, store, adapters, envelopes)


def _persist_envelopes(store: Store, adapters: list, envelopes: list) -> dict[str, Any]:
    """Perform blocking storage work off the event loop after all network calls finish."""
    results: dict[str, Any] = {}
    for (source_id, _, normalize), envelope in zip(adapters, envelopes, strict=True):
        if isinstance(envelope, BaseException):
            log.warning("Evidence ingestion %s failed: %s", source_id, type(envelope).__name__)
            store.record_ingestion(source_id, "failed", type(envelope).__name__)
            results[source_id] = {"status": "failed", "observations": 0, "rejected": 0}
            continue
        mode = envelope.get("source", "unavailable")
        series_available = source_id == "usgs_gage" and envelope.get("series_source", "unavailable") != "unavailable"
        if mode == "unavailable" and not series_available:
            store.record_ingestion(source_id, "unavailable", "Provider and cache unavailable")
            results[source_id] = {"status": "unavailable", "observations": 0, "rejected": 0}
            continue
        accepted, rejected = 0, 0
        try:
            rows = normalize(envelope)
        except (TypeError, ValueError, AttributeError) as exc:
            log.warning("Invalid evidence envelope from %s: %s", source_id, type(exc).__name__)
            store.record_ingestion(source_id, "failed", "Invalid provider response")
            results[source_id] = {"status": "failed", "observations": 0, "rejected": 1}
            continue
        for row in rows:
            try:
                store.add_observation({"source_mode": mode, **row})
                accepted += 1
            except (ValidationError, ValueError, TypeError) as exc:
                rejected += 1
                log.warning("Rejected %s evidence record: %s", source_id, type(exc).__name__)
        status = "partial" if rejected or (mode == "unavailable" and series_available) else mode
        store.record_ingestion(source_id, status,
                               f"{accepted} records accepted (including deduplicated repeats), {rejected} rejected",
                               envelope.get("fetched_at"))
        results[source_id] = {"status": status, "observations": accepted, "rejected": rejected}
    store.record_ingestion("drivetexas", "not_configured",
                           "DriveTexas adapter requires an approved API key and verified provider schema; no live road closure feed configured")
    results["drivetexas"] = {"status": "not_configured", "observations": 0, "rejected": 0}
    return results
